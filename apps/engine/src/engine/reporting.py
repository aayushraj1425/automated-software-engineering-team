"""Build a plain-English markdown report of an agent run — a shareable record
of what the team did.

A pure function over the run and its tasks: no model call, no database, no
network, so it works offline and is trivially testable. The report is assembled
from the run record the pipeline already writes, so it is always available, even
for a run whose workspace is long gone.

Design note: docs/architecture/runs-ui/RUN_REPORT.md.
"""

from collections.abc import Sequence

from engine.db.models import AgentRun, AgentTask


def _first_line(text: str | None, limit: int = 100) -> str:
    stripped = (text or "").strip()
    if not stripped:
        return ""
    line = stripped.splitlines()[0]
    return line if len(line) <= limit else line[: limit - 1] + "…"


_MAX_DECISIONS = 25


def build_run_report(
    run: AgentRun,
    tasks: list[AgentTask],
    repo_url: str | None,
    reasoning: Sequence[tuple[str | None, str]] | None = None,
) -> str:
    """One markdown document summarizing a run: request, plan, per-task outcome,
    the agents' key decisions, cost, and result. Defensive about unset fields so
    it works for a run in any state (a run that failed in planning has no tasks;
    a fresh one has no cost). `reasoning` is the run's `agent.reasoning` lines as
    `(agent role, text)` in chronological order — omitted for offline/fake runs,
    which produce none."""
    done = sum(1 for task in tasks if task.status == "done")
    lines: list[str] = [
        f"# Run report — {_first_line(run.request) or 'agent run'}",
        "",
        f"- **Status:** {str(run.status).replace('_', ' ')}",
        f"- **Repository:** {repo_url or 'not connected'}",
        f"- **Tasks:** {done}/{len(tasks)} completed",
        (
            f"- **Cost:** ${float(run.total_cost_usd or 0):.4f} "
            f"({run.total_input_tokens or 0} input / {run.total_output_tokens or 0} output tokens)"
        ),
    ]
    if run.pr_url:
        lines.append(f"- **Pull request:** {run.pr_url}")
    if run.error:
        lines.append(f"- **Failed:** {run.error}")

    lines += ["", "## Request", "", (run.request or "").strip() or "_none_"]

    summary = run.plan.get("summary") if isinstance(run.plan, dict) else None
    if summary:
        lines += ["", "## Plan", "", str(summary).strip()]

    if run.design_note:
        lines += ["", "## Principal Engineer design", "", run.design_note]
    if run.team:
        lines += ["", "## Team", ""]
        for seat in run.team:
            lines.append(
                f"- {seat.get('role', 'agent')} ({seat.get('level', 'engineer')}): "
                f"{seat.get('model') or 'no model required'}"
            )
    if run.preview_deployment:
        preview = run.preview_deployment
        lines += [
            "",
            "## Preview",
            "",
            f"**Status:** {preview.get('status', 'unknown')}",
            f"**Namespace:** {preview.get('namespace', 'none')}",
        ]
        if preview.get("url"):
            lines.append(f"**URL:** {preview['url']}")
        if preview.get("expires_at"):
            lines.append(f"**Expires:** {preview['expires_at']}")
        smoke = preview.get("smoke")
        if isinstance(smoke, dict):
            lines.append(f"**Cloud smoke tests:** {'passed' if smoke.get('passed') else 'failed'}")
        if preview.get("status") == "simulated":
            lines.append("Offline simulation; no live cloud resource was deployed.")

    if run.test_report:
        report = run.test_report
        lines += [
            "",
            "## Test report",
            "",
            f"**Tests:** {report.get('status', 'unknown')}",
            f"**Scope:** {report.get('scope', 'repository test suite')}",
            f"**Command:** {report.get('test_command') or 'not run'}",
            f"**Reason:** {report.get('reason') or 'none'}",
            "",
            str(report.get("output") or "_No test output._"),
        ]

    if tasks:
        lines += ["", "## Tasks", ""]
        for task in tasks:
            status = str(task.status).replace("_", " ")
            lines.append(f"{task.sequence}. **{task.title}** — _{task.role}_ · {status}")
            if task.result:
                lines.append(f"   - {str(task.result).strip()}")

    shown = [(agent, _first_line(text, 240)) for agent, text in (reasoning or []) if text.strip()]
    if shown:
        lines += ["", "## Decisions", ""]
        for agent, text in shown[:_MAX_DECISIONS]:
            lines.append(f"- _{agent or 'system'}_: {text}")
        if len(shown) > _MAX_DECISIONS:
            lines.append(f"- _… and {len(shown) - _MAX_DECISIONS} more_")

    lines += ["", "---", "", "_Generated by ASEP from the run record._", ""]
    return "\n".join(lines)
